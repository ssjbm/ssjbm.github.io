<grostitre>Introduction</grostitre>


<p>Lorsque l'on veut tenir une assemblée générale de section, un membre de la permanence de la Société Saint-Jean-Baptiste contactera le président de la section pour réserver la date de l’assemblée de votre section. </p>

<p>Les sections doivent tenir au moins une assemblée générale par année, durant laquelle les dirigeants et  les délégués sont élus. Durant la période du 15 janvier au 15 février, un maximum de trois assemblées  générales peuvent se faire à la même date, et ce, pour toutes les sections. Tous les membres de la section,  les conseillers généraux, les candidats au conseil général et autres observateurs peuvent assister à  l’assemblée générale de la section, mais seuls les membres actifs de la section ont le droit de parole et  seuls les membres actifs depuis trois mois ont droit de vote. </p>

<dots></dots><br>


<Grostitre>L'avis de convocation</Grostitre>

<p>L’avis de convocation sera préparé et transmis par la permanence de la SSJB, par courriel et par la poste, au nom du président de la section. Les frais postaux (timbres) seront ensuite facturés à la section.</p>

<dots></dots><br>


<grostitre>Le quorum</grostitre>

<p>Le quorum de l'assemblée générale de section est de dix membres actifs en règle sauf pour les sections  qui comptent cent membres ou moins, pour lesquelles le quorum est fixé à huit. (Article 18.D) </p>

<dots></dots><br>


<grostitre>Les procédures</grostitre>

<p>Habituellement, les procédures ne changent pas d'une assemblée à l'autre. Le président de la section  assume l’animation ; toutefois, il peut déléguer cette tâche à quelqu'un d'autre. Le secrétaire de la section  assume la rédaction des avis de convocation et des procès-verbaux des deux instances ; c'est d'ailleurs  son rôle principal. Le quorum des réunions du Conseil de section est évidemment différent du quorum  exigé lors d'une assemblée générale. </p>

<dots></dots><br>


<grostitre>Les étapes de déroulement</grostitre>


<h3>➲ Proposition</h3>

<p>L'étape de la prise de décision débute par la formulation d'une proposition de la part d'un membre  (proposeur). Pour présenter une proposition, le membre devrait lever la main et attendre l'autorisation  du président. » (réf. : Procédures de réunion pour les cercles de jeunes ruraux, A.J.R.Q., 1984, p. 18).  Quand il a reçu le droit de parole, le proposeur formule tout haut sa proposition : ex. : Je propose que...  Pour qu'un vote se prenne sur cette proposition, celle-ci doit être appuyée par un autre membre.  L'assemblée ne doit traiter qu'une seule proposition à la fois. </p>



<h3>➲ Amendement</h3>

<p>Un membre a formulé une proposition. Celle-ci a été appuyée, l'assemblée est en train de la débattre  mais le vote relatif à cette proposition n'a pas encore eu lieu. Un autre membre est en accord avec l'idée  de base de cette proposition mais désire remplacer, ajouter ou biffer certains mots. S'il fait part de ses intentions au président, on dira alors qu'il formule un amendement. » (réf. : Procédures de réunion pour  les cercles de jeunes ruraux, A.J.R.Q., 1984, p.20). </p>

<p>Un vote devrait se prendre sur cet amendement. Si l'amendement est rejeté, la proposition restera telle  quelle, s’il est accepté, la proposition sera reformulée selon l'amendement. </p>


<h3>➲ Sous-amendement</h3>

<p>De la même façon, un sous-amendement peut venir modifier un amendement. </p>


<h3>➲ Résolution</h3>

<p>Une résolution est une proposition adoptée. </p>



<h3>➲ Question préalable</h3>

<p>Si un membre juge que les discussions se prolongent inutilement au sujet d'une proposition, d'un  amendement ou d'un sous-amendement, il peut demander qu'un vote soit pris immédiatement. On dit  alors qu'il pose la question préalable. » (réf. : Procédures de réunion pour les cercles de jeunes ruraux,  A.J.R.Q., 1984, p. 22). Cette question préalable sera généralement rejetée par le président, si le membre  qui demande la question préalable n'a pas attendu son tour de parole et si elle n'est pas appuyée. </p>

<p>Quand la question préalable est posée, le président doit faire arrêter la discussion et en informer les  membres et s'il y a des membres qui attendent un droit de parole, le président invitera le proposeur de  la question préalable à retirer sa proposition. Le proposeur n'est pas tenu de le faire. S'il ne la retire pas,  le vote sera pris immédiatement. La question préalable exige un vote des deux tiers. </p>



<h3>➲ Question de privilège</h3>

<p>Une question de privilège peut être demandée lorsqu'il y a violation des droits des membres. Celui qui  demande la question de privilège doit en exposer les raisons et c'est le président qui décidera d'accorder  ou de refuser la question de privilège. </p>


<h3>➲ Rappel au règlement</h3>

<p>Au cours d'un débat, un membre peut toujours soulever un rappel au règlement pour rétablir les faits,  pour protester contre un langage grossier, des injures ou pour exiger qu'un autre membre s'en tienne au  sujet en discussion. Celui qui soulève le rappel au règlement doit l'expliquer brièvement et le président  juge si l'on doit en tenir compte.</p>



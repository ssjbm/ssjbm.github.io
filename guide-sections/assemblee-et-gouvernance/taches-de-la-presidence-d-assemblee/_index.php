<grostitre>Préparation d’une assemblée</grostitre>

<ol>
    <li>Contacter les autres membres du conseil</li>
    <li>Inventorier les questions à soumettre à l'assemblée</li>
    <li>Se renseigner sur les sujets concernés</li>
</ol>

<dots></dots><br>


<grostitre>Vérifier...</grostitre>

<ol>
    <li>Si tous les participants ont bien été convoqués au moins 7 jours francs avant l'assemblée</li>
    <li>Tous les aspects techniques (le lieu, la disposition, la décoration, le goûter)</li>
    <li>Que la correspondance, les comptes à présenter, le procès-verbal, les communications dans les  journaux locaux et tout autre document sont en ordre </li>
    <li>Que les rapports du trésorier et des responsables de projets soient prêts</li>
    <li>Que les invités spéciaux seront présents s'il y a lieu et prévoir le moment et la durée des interventions.</li>
</ol>

<dots></dots><br>


<grostitre>Conseils et suggestions</grostitre>


<ul>
    <li>Accueillir chaleureusement chaque participant et faire les présentations qui s'imposent</li>
    <li>Commencer la séance à l'heure déterminée</li>
    <li>Suivre l'ordre du jour tel qu'adopté</li>
    <li>Obtenir l'opinion et la participation des membres en respectant la personnalité de chacun</li>
    <li>Allouer un temps limite d'intervention et respecter le droit de parole de chacun</li>
    <li>Noter et ordonner les bonnes idées qui surgissent au cours des débats</li>
    <li>Ne pas permettre de discussion si une proposition en bonne et due forme n'a pas été présentée  à l'assemblée</li>
    <li>Maintenir l'ordre selon la procédure démocratique durant les discussions importantes et malgré  les divergences d'opinion</li>
    <li>Résumer objectivement de temps à autre l'état du débat afin d'arriver le plus tôt possible à une  décision finale</li>
    <li>Le président s'assure après la séance que chaque responsable a bien compris sa tâche et que les décisions  prises par l'assemblée seront exécutées</li>
</ul>

<dots></dots>


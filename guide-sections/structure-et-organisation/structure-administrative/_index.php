<grostitre>Président Général</grostitre>

<p>Le président est élu lors de l’assemblée générale annuelle ; il est élu pour des mandats de 2 ans. Le président général préside les séances du  conseil général ; il surveille les affaires de la Société, assure l’exécution des statuts, règlements, règles et  ordonnances, tout en restant subordonné à l’autorité du conseil général ; il est de droit membre de toutes  les commissions et de tous les comités. Le président général ou la personne qu’il désigne ou que le conseil  général désigne est le seul porte-parole officiel de la Société. </p>

<dots></dots><br>


<grostitre>Vice-président</grostitre>

<p>Le vice-président prête assistance au président, et en son absence, remplit ses fonctions. </p>

<dots></dots><br>


<grostitre>Trésorier Général</grostitre>

<p>Le trésorier général fait rapport au conseil général, mensuellement ou lorsqu’il est requis, de l’état  financier de la Société, des placements de fonds, etc. Il soumet à l’assemblée générale annuelle un état  complet et détaillé des opérations financières de la Société, certifié par les auditeurs. </p>

<dots></dots><br>


<grostitre>Direction Générale</grostitre>

<p>Sous la supervision du Conseil, il désigne le personnel et assume l’ensemble des responsabilités inhérentes à cette fonction.</p>


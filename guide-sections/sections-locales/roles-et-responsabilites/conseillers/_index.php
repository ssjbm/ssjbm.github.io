<grostitre>Description de poste</grostitre>

<p>Les conseillers de la section soutiennent le président, le secrétaire et le trésorier dans l’exécution de leurs fonctions, et peuvent les remplacer au besoin. Ils sont appelés à contribuer à la mise en œuvre d’initiatives favorisant la vitalité et le rayonnement de la section.</p>

<dots></dots><br>


<grostitre>Responsabilités</grostitre>

<p>Certaines tâches ou responsabilités spécifiques peuvent leur être confiées par le conseil de section, selon les besoins et les compétences disponibles. À titre d’exemple, un ou plusieurs conseillers pourraient être appelés à :</p>

<ol>
    <li>Contribuer à la promotion de l’éducation nationale dans leur milieu.</li>
    <li>Utiliser le matériel promotionnel disponible afin de sensibiliser la population aux enjeux nationaux.</li>
    <li>Collaborer à des projets de sections et aussi des projets communs avec d'autres sections.</li>
    <li>Participer à la mise en place et à la coordination d’un réseau de communication entre les membres (ex. : courriel, facebook etc.).</li>
    <li>Soutenir la réalisation de campagnes locales.</li>
    <li>Participer à la sollicitation d’adhésions et à l’intégration des nouveaux membres.</li>
    <li>Encourager la relève en identifiant et en motivant de nouveaux militants.</li>
    <li>Prendre part aux diverses activités de la Société, notamment l’assemblée générale annuelle et les campagnes de financement.</li>
</ol>


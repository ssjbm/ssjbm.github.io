<grostitre>Description de poste</grostitre>

<p>Le conseiller jeunesse doit participer aux réunions et aux activités de la section et du conseil jeunesse et  tenir au courant le conseil de la section des projets et des réalisations du conseil jeunesse. Il informe les  jeunes de sa section sur les activités du conseil jeunesse et suscite leur implication. Il s'implique dans le  recrutement de jeunes dans sa section. Il assure la promotion du plan d'action du conseil jeunesse dans  son milieu de vie. </p>

<dots></dots><br>


<grostitre>Responsabilités</grostitre>

<ol>
    <li>Il assure la sollicitation publique dans l'institution scolaire qu'il fréquente ou dans son milieu de vie</li>
    <li>Il publie des articles dans les journaux étudiants et les journaux locaux. </li>
    <li>Il travaille en collaboration avec la section et le conseil jeunesse. </li>
    <li>Il participe aux diverses activités de la Société, telles que les journées d'études, l’assemblée  générale annuelle, la vente d'articles promotionnels lors de différentes campagnes. </li>
</ol>


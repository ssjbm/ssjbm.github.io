<grostitre>Description de poste</grostitre>

<p>Le président voit à l’exécution des décisions de l’assemblée générale et du conseil de section et des  décisions du conseil général, coordonne le travail et les initiatives de la section et tient le conseil général  au courant des projets et des réalisations de sa section. Il convoque ou fait convoquer les réunions du  conseil de section. Si le président cesse d’exercer ses fonctions, le vice-président ou à défaut le secrétaire,  convoque dans les trente jours de la cessation le conseil de section qui procède à l’élection d’un président. </p>

<dots></dots><br>


<grostitre>Responsabilités</grostitre>



<ol>
    <li>Il convoque et préside au moins quatre assemblées régulières du conseil de la section (art. 17.A) et  une assemblée générale de section (art. 18.A) durant laquelle les dirigeants et les délégués sont  élus. </li>
    <li>Il voit en collaboration avec le secrétaire à ce que tous les procès-verbaux soient acheminés à la  Société (secrétariat) (art. 13.C). </li>
    <li>Il voit en collaboration avec le trésorier à ce que le rapport annuel de section soit acheminé à la  Société (registrariat) dans les délais prévus (art. 13.D). </li>
    <li>Il voit à l'élaboration et à la réalisation des différents projets et activités de la section.</li>
    <li>Il assiste ou se fait représenter, à la commission des présidentes et présidents, à cinq reprises durant l’année, soit aux mois de janvier, mars, mai, septembre et novembre.</li>
    <li>Il informe les conseillers de sa section des décisions et des prises de position du conseil général et  de la commission des présidentes et présidents. </li>
    <li>Il transmet au conseil général (lors de la commission des présidentes et présidents) les  recommandations de sa section. </li>
    <li>Il participe aux diverses activités de la Société telles que l’assemblée générale  annuelle, les campagnes de financement. </li>
    <li>Il motive ses membres et les incite à participer aux activités de la Société ainsi qu'à celles des  autres sections. </li>
    <li>Il évalue l'efficacité de la section et propose des solutions aux problèmes qu'elle rencontre avec la  collaboration du coordonnateur de projets.</li>
</ol>

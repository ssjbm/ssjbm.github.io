<grostitre>Description de poste</grostitre>

<p>Le vice-président prête assistance au président et, en son absence, remplit ses fonctions. </p>

<dots></dots><br>


<grostitre>Responsabilités</grostitre>



<ol>
    <li>Il seconde le président dans l'élaboration et la réalisation des différents projets et activités de la  section. </li>
    <li>En l'absence du président, il représente la section aux diverses réunions et activités.</li>
    <li>Il participe aux diverses activités de la Société telles que les journées d'études, l'assemblée générale  annuelle, les campagnes de financement.</li>
    <li>En collaboration avec le président, il motive les membres et les incite à participer aux activités de la  Société ainsi qu'à celles des autres sections. </li>
    <li>Il collabore avec les autres membres de l'exécutif à rendre représentative la section dans son milieu. </li>
    <li>En collaboration avec le président, il coordonne le travail des conseillers et les membres de la  section. </li>
</ol>

<grostitre>Description de poste</grostitre>

<p>Le secrétaire fait la correspondance, rédige les procès-verbaux et les rapports et donne les avis requis. Il  enregistre la présence des membres aux assemblées, assume la garde des archives, registres, volumes,  documents et biens de la section. Il transmet aux dates spécifiées au secrétariat de la Société tous les  rapports officiels : élection des dirigeants de la section, délégués à l'assemblée générale annuelle, les  copies des procès-verbaux du conseil de section ainsi que toutes les autres communications qu'exige le  conseil général. </p>

<dots></dots><br>


<grostitre>Responsabilités</grostitre>

<ol>
    <li>Il convoque les assemblées des membres de la section en leur adressant les avis requis. </li>
    <li>Il rédige les procès-verbaux de toutes les réunions du conseil de section, de l'assemblée générale de  janvier (ou février) et de tout autre assemblée générale spéciale. </li>
    <li>Il remet à la société (secrétariat) une copie de tous les procès-verbaux des réunions du conseil de  section, de l'assemblée générale de janvier et de tout autre assemblée générale spéciale. </li>
    <li>Il effectue, en collaboration avec le président, la correspondance de la section ainsi que celle  concernant les relations avec les différents organismes du milieu. </li>
    <li>Il participe aux diverses activités de la Société telles que les journées d'études, l’assemblée générale  annuelle, les campagnes de financement. </li>
</ol>

<dots></dots><br>


<grostitre>Règles d’application</grostitre>

<p>Dès la fin de l'assemblée générale annuelle de janvier (ou février), obtenir de l'ancien(ne) secrétaire tous  les documents et procès-verbaux qu'il a en sa possession.</p>

<dots></dots><br>


<grostitre>Renseignements utiles</grostitre>

<p>Dans son procès-verbal, le secrétaire indique la date, l'heure et le lieu de l'assemblée, les personnes  présentes et les absences motivées. Il rapporte les décisions de l'assemblée, à commencer par l'adoption  du dernier procès-verbal avec les corrections apportées, s'il y a lieu. Lorsqu'une décision est précédée de  discussions importantes et de divergences d'opinion, le secrétaire en fait état brièvement. Le secrétaire  inscrit et précise dans chaque cas les autorisations de payer les comptes et d'effectuer les dépenses. Le  secrétaire résume dans le procès-verbal les rapports présentés et indique si l'assemblée les a reçus ou  adoptés. Il transmet les amendements aux règlements ainsi que les propositions pour l’assemblée générale annuelle. Le secrétaire indique la date et l'heure de la prochaine réunion. Lors de l’assemblée, le secrétaire dispose de : </p>

<ol>
    <li>la liste des participants convoqués. Cela permet de vérifier si le membre est en règle et facilite la  notation des présences. </li>
    <li>le procès-verbal de l'assemblée précédente. Il en fera la lecture. Le président demandera à  l'assemblée si le procès-verbal est conforme. Si oui, l'assemblée l'adoptera et le président et le secrétaire  le signeront. Sinon, avant de procéder à l'adoption, le secrétaire effectuera les corrections qui s'imposent. </li>
    <li>la correspondance et autres documents à soumettre à l'assemblée, les rapports qu'il a fait  parvenir à la Société. Il donnera des renseignements brefs sur le courrier et les documents reçus. </li>
</ol>

<info>Le secrétaire fait parvenir une copie de tous les procès-verbaux ainsi que tout autre document à  l'attention du chargé de projets au secrétariat de la Société.</info>



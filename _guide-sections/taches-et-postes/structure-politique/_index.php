<grostitre>Assemblée générale annuelle</grostitre>

<p>Lors de l’assemblée générale annuelle des membres, seuls ont le droit de vote les conseillers généraux, les membres délégués d’office et les membres délégués par les sections. Les conseillers généraux sortant  de charge bénéficient du statut de délégués à l’assemblée générale annuelle jusqu’à la fin de cette  dernière. Si, durant l’année, une assemblée générale extraordinaire est convoquée, les membres qui y  ont droit de vote sont les mêmes. </p>

<dots></dots><br>


<grostitre>Comité de vérification des finances</grostitre>

<p>Le comité de vérification des finances se compose de cinq membres actifs et du trésorier général qui en  est membre d’office. Les cinq membres du comité de vérification sont élus par l’assemblée générale  annuelle. Le mandat des cinq membres de ce comité est de 2 ans.  </p>

<dots></dots><br>


<grostitre>Conseil général</grostitre>

<p>La Société est dirigée par un conseil général. Pour être élu au poste de conseiller général, le membre doit  être actif depuis au moins trois mois précédant son élection, être âgé d’au moins 18 ans et ne pas être un  employé rémunéré de la Société, ou de l’un ou l’autre de ses services, organismes, institutions ou filiales. Le conseil général se réunit au moins une fois par mois, sauf en juillet et en août, à la date qu’il a  préalablement fixée. Il se réunit aussi sur convocation extraordinaire du président général ou à la  demande de trois de ses membres. </p>

<dots></dots><br>


<grostitre>Comité de direction</grostitre>

<p>Le conseil général constitue, parmi les conseillers généraux, son comité de direction à la première réunion  qui suit l’assemblée générale annuelle. Le comité de direction doit comprendre, outre la présidence  générale, deux vice-présidents généraux, un secrétaire général et un trésorier général. Le comité de  direction dont trois membres forment le quorum voit à l’expédition des affaires courantes de la Société.  Il se réunit sur la convocation de la présidence générale et fait rapport de ses recommandations au conseil  général. </p>

<dots></dots><br>


<grostitre>Comission des présidentes et présidents</grostitre>

<p>La commission des présidents constitue un comité consultatif permanent du conseil général. Elle est  composée des présidents de section, ou de leurs représentants Toutefois, seuls les présidents de section  et le président du conseil jeunesse ou leurs représentants ont droit de vote lors des réunions de la  commission des présidents et, jusqu’à concurrence d’un vote maximum par section. </p>

<dots></dots><br>


<grostitre>Conseil jeunesse</grostitre>

<p>Le conseil jeunesse constitue un comité consultatif permanent du conseil général ainsi qu’un comité  d’action pour promouvoir les objectifs de la Société. Il se réunit 2 fois par année et se compose d’un  représentant âgé de 16 à 30 ans inclusivement, élu par chacune des sections, d’un conseiller général  délégué par le conseil général et du président général d’office. Il se compose également d’un comité de  direction d’au moins sept (7) membres élus par et parmi les membres de la Société âgés de 16 à 30 ans  réunis en assemblée générale. Le comité de direction administre les affaires du conseil jeunesse,  notamment les budgets et les dépenses du conseil jeunesse.</p>


<grostitre>Fonctionnement d'une section</grostitre>


<p>Toute section doit compter au moins vingt membres actifs. Chaque section devrait-être dirigée par un conseil  composé d’au moins sept membres actifs. Ce conseil se compose d’un président, d’un vice-président, d’un  secrétaire, d’un trésorier, d’un conseiller jeunesse et d’au moins deux conseillers. Le choix du nombre de  conseillers est déterminé annuellement par l’assemblée générale. </p>

<p>Pour être élu à l’une des fonctions du conseil de section ou de délégué à l’assemblée générale annuelle,  le membre doit avoir été membre actif depuis au moins trois mois avant son élection, ne pas être un  employé ou un administrateur rémunéré de la Société ou de l’un de ses organismes, filiales ou institutions  et ne pas être un membre du conseil général. Le membre actif élu à une fonction au conseil de section  peut être candidat au conseil général. S’il est élu conseiller général, il doit démissionner de l’une des deux  fonctions dans les trente jours suivant la clôture de l’assemblée générale annuelle de la SSJBM où il a été  élu.</p>

